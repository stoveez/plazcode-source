#!/usr/bin/env python3
"""Builds PlazLib's data file from its Luau source (owner, 2026-11-19).

Reads   development/<ver>/plazlib/plazlib.luau   (the helpers, marked with --@helper and --@doc)
Writes  development/<ver>/overlay/core/plazlib-data.js
        PlazCodePlazLibData = { VERSION, ORDER, NEEDS, DEFINES, code() -> {helper: one-line Luau}, doc() -> catalog text }
The injection logic is ts/core/plazlib.ts (core/plazlib.js). One source for the helpers AND what the AI is told about them,
so the two cannot disagree.

Run:  python3 development/1.24.35/plazlib/build_plazlib.py           write the file
      python3 development/1.24.35/plazlib/build_plazlib.py --check   fail if the committed file is out of date
"""
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "plazlib.luau"
TARGET = HERE.parent / "overlay" / "core" / "plazlib-data.js"
VERSION = "1"


def code_part(line):
    """The line without a trailing comment, or raise if a comment sits after code (the helpers are joined into one line)."""
    quote = None
    i = 0
    while i < len(line):
        ch = line[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif line.startswith("--", i):
            raise SystemExit(f"plazlib.luau: comment after code is not allowed (helpers are joined into one line): {line.strip()}")
        elif line.startswith("[[", i) or line.startswith("[=", i):
            raise SystemExit(f"plazlib.luau: long strings are not allowed (use NL): {line.strip()}")
        i += 1
    if quote:
        raise SystemExit(f"plazlib.luau: a string runs past the end of the line: {line.strip()}")
    return line


def parse():
    helpers, order, current = {}, [], None
    for raw in SOURCE.read_text(encoding="utf-8").splitlines():
        stripped = raw.strip()
        m = re.match(r"^--@helper\s+(\w+)(?:\s+needs=([\w,]+))?\s*$", stripped)
        if m:
            name = m.group(1)
            if name in helpers:
                raise SystemExit(f"plazlib.luau: helper {name} twice")
            current = {"needs": [n for n in (m.group(2) or "").split(",") if n], "code": [], "doc": [], "defines": []}
            helpers[name] = current
            order.append(name)
            continue
        if stripped.startswith("--@doc "):
            if current is None:
                raise SystemExit("plazlib.luau: --@doc before the first --@helper")
            current["doc"].append(stripped[7:].strip())
            continue
        if not stripped or stripped.startswith("--"):
            continue
        if current is None:
            raise SystemExit(f"plazlib.luau: code before the first --@helper: {stripped}")
        if stripped[0] in "([":
            raise SystemExit(f"plazlib.luau: a line may not start with '(' or '[' (ambiguous once joined): {stripped}")
        current["code"].append(code_part(stripped))
        d = re.match(r"^PL\.([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)?)\s*=", raw)
        if d and not raw[0].isspace():
            current["defines"].append(d.group(1))
    for name, h in helpers.items():
        for need in h["needs"]:
            if need not in helpers:
                raise SystemExit(f"plazlib.luau: {name} needs unknown helper {need}")
        if not h["defines"]:
            raise SystemExit(f"plazlib.luau: helper {name} defines nothing")
    return helpers, order


def render(helpers, order):
    defines = {}
    for name in order:
        for d in helpers[name]["defines"]:
            if d in defines:
                raise SystemExit(f"plazlib.luau: PL.{d} defined by {defines[d]} and {name}")
            defines[d] = name
    code = {name: " ".join(helpers[name]["code"]) for name in order}
    doc_lines = [line for name in order for line in helpers[name]["doc"]]
    doc = "\n".join("- " + line for line in doc_lines)
    j = lambda v: json.dumps(v, ensure_ascii=False)
    lines = [
        "// SPDX-License-Identifier: LicenseRef-PlazCode-Proprietary",
        "// GENERATED by development/1.24.35/plazlib/build_plazlib.py from plazlib/plazlib.luau. Do not edit: change the .luau file and run the script.",
        "// PlazLib's helpers as one-line Luau (injected by core/plazlib.js) and the catalog the AI reads. The texts sit inside functions,",
        "// so a release can move them into the sealed text pack (protection.mjs TEXT_PACK_FILES).",
        "const PlazCodePlazLibData = (() => {",
        f"  const VERSION = {j(VERSION)};",
        f"  const ORDER = {j(order)};",
        f"  const NEEDS = {j({n: helpers[n]['needs'] for n in order})};",
        f"  const DEFINES = {j(defines)};",
        "  function code() {",
        "    return {",
    ]
    for name in order:
        lines.append(f"      {j(name)}: {j(code[name])},")
    lines += [
        "    };",
        "  }",
        "  function doc() {",
        f"    return {j(doc)};",
        "  }",
        "  return { VERSION, ORDER, NEEDS, DEFINES, code, doc };",
        "})();",
        "if (typeof module !== \"undefined\" && module.exports) module.exports = PlazCodePlazLibData;",
        "",
    ]
    return "\n".join(lines)


def main():
    helpers, order = parse()
    out = render(helpers, order)
    if "--check" in sys.argv:
        now = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if now.replace("\r\n", "\n") != out:
            raise SystemExit(f"OUT OF DATE {TARGET.name}: run python3 development/1.24.35/plazlib/build_plazlib.py")
        print(f"ok {TARGET.name}: {len(order)} helpers")
        return
    TARGET.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.name}: {len(order)} helpers, {sum(len(v) for v in [' '.join(helpers[n]['code']) for n in order])} characters of Luau")


if __name__ == "__main__":
    main()
