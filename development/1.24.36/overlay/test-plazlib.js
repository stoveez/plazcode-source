// PlazLib (owner, 2026-11-19): PL.* Luau helpers injected into build code only when used. Run: node test-plazlib.js
// With the official Luau VM (PLAZCODE_LUAU, or next to PLAZCODE_LUAU_COMPILE) every helper also runs against Roblox
// stand-ins (release-tools/plazlib-mock.luau) and every script the helpers write is compiled.
const assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path"), cp = require("node:child_process"), os = require("node:os"), vm = require("node:vm");
global.PlazCodePlazLibData = require("./core/plazlib-data.js");
const L = require("./core/plazlib.js");
const D = global.PlazCodePlazLibData;

// 1. Injection.
assert.deepEqual(L.inject("print(1)"), { code: "print(1)", used: [] }, "code without PL is untouched");
const src = 'local floor = PL.part{name="Floor", size={64,1,64}}\nlocal y = 2\nreturn floor.Name';
const one = L.inject(src);
assert.deepEqual(one.used, ["part"]);
assert(one.code.startsWith(L.MARK) && one.code.endsWith(src), "helpers go in front of the AI's code");
const prelude = one.code.slice(0, one.code.length - src.length);
assert(!prelude.includes("\n"), "the helpers sit on the first line, so the AI's line numbers do not move");
for (const need of ["PL.part =", "PL.vec =", "PL.color =", "PL.enum =", "PL.need =", "PL.find ="]) assert(prelude.includes(need), need);
assert(!prelude.includes("PL.touchPad =") && !prelude.includes("PL.ui"), "only what the code uses");
assert.equal(L.inject(one.code).code, one.code, "never injected twice");
const ui = L.inject('local g = PL.ui.screen("Shop")\nPL.ui.button(g, "Buy")');
assert.deepEqual(ui.used.sort(), ["ui", "uibutton"]);
const bad = L.inject("PL.frobnicate()\nPL.part{}");
assert.match(bad.error, /PL\.frobnicate is not a PlazLib helper/); assert.match(bad.error, /PL\.part/); assert.match(bad.error, /Nothing was run/);
assert.deepEqual(L.inject('print("use PL.part later") -- PL.weld in a comment').used, [], "PL in strings and comments does not count");
assert.deepEqual(L.inject("local PL = require(game.ReplicatedStorage.PL)\nPL.part()").used, [], "the AI's own PL table is left alone");
assert.deepEqual(L.namesIn("PL.tokens().palette PL.ui.frame(x) PL.version"), ["tokens", "ui.frame", "version"]);
assert.equal(L.inject("PL.weldAll(m)").used[0], "weldAll");
assert.deepEqual(L.inject("print(1)", null), { code: "print(1)", used: [] }, "no library loaded: nothing happens");

// 2. One catalog for the helpers and the AI's text.
const ref = L.reference();
for (const name of ["PL.find", "PL.color", "PL.vec", "PL.part", "PL.model", "PL.weld", "PL.weldAll", "PL.tween", "PL.touchPad", "PL.udim2", "PL.tokens", "PL.ui.screen", "PL.ui.frame", "PL.ui.text", "PL.ui.list", "PL.ui.button"]) {
  assert(ref.includes(name + "(") || ref.includes(name + "{"), "the AI is told about " + name);
  assert(L.inject(name.replace(/^PL\./, "PL.") + "()").used.length, name + " is really injectable");
}
assert.match(ref, /never use PL inside a Script, LocalScript or ModuleScript/);
const gen = fs.readFileSync("core/plazlib-data.js", "utf8");
assert.match(gen, /GENERATED by development\/1\.24\.36\/plazlib\/build_plazlib\.py/);
assert.match(gen, /function code\(\) \{\n    return \{/, "the helper texts sit inside a function (text pack)");

// 3. Wiring: loaded before main.js, injected before chunking, protected in releases, routed to build requests.
const manifest = JSON.parse(fs.readFileSync("manifest.json", "utf8"));
for (const cs of manifest.content_scripts.filter((c) => c.js.includes("core/main.js"))) {
  const at = (f) => cs.js.indexOf(f);
  assert(at("core/plazlib-data.js") > -1 && at("core/plazlib-data.js") < at("core/plazlib.js") && at("core/plazlib.js") < at("core/main.js"), cs.matches[0]);
}
const main = fs.readFileSync("core/main.js", "utf8");
const inj = main.indexOf("PlazCodePlazLib.inject(args.code)"), chunk = main.indexOf("const pieces = splitLuauChunks(args.code, LUAU_CHUNK_MAX);");
assert(inj > 0 && chunk > inj, "helpers are added before big code is split into chunks");
const lean = fs.readFileSync("core/lean-startup.js", "utf8");
assert.match(lean, /name: "plazlib"/); assert.match(lean, /PlazCodePlazLib\.reference\(\)/);
const protection = path.join(__dirname, "..", "protection.mjs");
if (fs.existsSync(protection)) assert.match(fs.readFileSync(protection, "utf8"), /'core\/plazlib-data\.js':'plazlib'/);
if (fs.existsSync("core/config.js") && fs.existsSync("core/chat-creators.js")) {
  const context = vm.createContext({ window: { __rsThinkingLevel: () => "default" }, console });
  for (const f of ["core/luau-knowledge.js", "core/chat-creators.js", "core/ultracode.js", "core/clarification.js", "core/config.js", "core/plazlib-data.js", "core/plazlib.js", "core/lean-startup.js"]) vm.runInContext(fs.readFileSync(f, "utf8"), context, { filename: f });
  const Lean = vm.runInContext("PlazCodeLeanStartup", context);
  assert(Lean.routeTopics("build a small house with two doors and a jump pad", { engine: "roblox" }).includes("plazlib"));
  assert(!Lean.routeTopics("hi, how are you?", { engine: "roblox" }).includes("plazlib"));
}

