if (!vmPath || !fs.existsSync(vmPath)) {
  if (process.env.PLAZCODE_REQUIRE_LUAU === "1") throw new Error("the official Luau VM is required here but was not found at " + vmPath);
  console.log("PASS plazlib (Luau run skipped: no Luau VM; CI runs it)");
  process.exit(0);
}
